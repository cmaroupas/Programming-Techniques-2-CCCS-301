// Abstract class for room decorators
abstract class RoomDecorator implements Room {
    protected Room room;

    public RoomDecorator(Room room) {
        this.room = room;
    }

    public int getPrice() {
        return room.getPrice();
    }

    public String getDescription() {
        return room.getDescription();
    }

    public boolean getReservationStatus() {
        return room.getReservationStatus();
    }

    public boolean reserveTheRoom(RoomType roomType) {
        return room.reserveTheRoom(roomType);
    }
}
// Concrete decorator class for adding a view to a room
class WithView extends RoomDecorator {
    private int price = 50;

    public WithView(Room room) {
        super(room);
    }

    public int getPrice() {
        return super.getPrice() + price;
    }

    public String getDescription() {
        return super.getDescription() + " + With view";
    }
}
