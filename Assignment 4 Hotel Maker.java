// An enumeration of the available room types in the hotel: SINGLE, DOUBLE, and DELUXE.
enum RoomType {
    SINGLE, DOUBLE, DELUXE;
}
/**
 The Room interface defines the methods that all room types must implement.
 getPrice() returns the price of the room.
 getDescription() returns the description of the room.
 getReservationStatus() returns whether the room is reserved or not.
 reserveTheRoom() reserves the room with the given RoomType.
 */
interface Room {
    int getPrice();

    String getDescription();

    boolean getReservationStatus();

    boolean reserveTheRoom(RoomType roomType);
}

/**
 Implementation of the Room interface for a Single Room.
 */
class SingleRoom implements Room {
    private int price = 50;
    private String description = "Single Room";
    private boolean isReserved = false;

    /**

     Returns the price of the room.
     @return the price of the room
     */
    public int getPrice() {
        return price;
    }
    /**

     Returns the description of the room.
     @return the description of the room
     */
    public String getDescription() {
        return description;
    }
    /**

     Returns the reservation status of the room.
     @return the reservation status of the room
     */
    public boolean getReservationStatus() {
        return isReserved;
    }
    /**

     Reserves the room if it is not already reserved and if the room type is SINGLE.
     @param roomType the room type requested
     @return true if the room is reserved, false otherwise
     */
    public boolean reserveTheRoom(RoomType roomType) {
        if (roomType == RoomType.SINGLE) {
            if (!isReserved) {
                isReserved = true;
                return true;
            }
        }
        return false;
    }
}
